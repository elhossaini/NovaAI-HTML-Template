function applyLanguage(lang) {
  const dict = translations[lang] || translations.en;
  const isAr = lang === "ar";
  document.documentElement.setAttribute("lang", lang);
  document.documentElement.setAttribute("dir", isAr ? "rtl" : "ltr");
  document.title = dict.pageTitle;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      el.textContent = dict[key];
    }
  });

  const langToggle = document.getElementById("langToggle");
  if (langToggle) {
    langToggle.textContent = dict.langToggle;
  }

  localStorage.setItem("nova-lang", lang);
}

const langToggle = document.getElementById("langToggle");
const savedLang = localStorage.getItem("nova-lang") || "en";
applyLanguage(savedLang);

if (langToggle) {
  langToggle.addEventListener("click", () => {
    const currentLang = document.documentElement.getAttribute("lang") === "ar" ? "ar" : "en";
    applyLanguage(currentLang === "ar" ? "en" : "ar");
  });
}

// Mobile Navigation Toggle
const menuToggle = document.getElementById('menuToggle');
const navLinks = document.getElementById('navLinks');

if (menuToggle && navLinks) {
  menuToggle.addEventListener('click', () => {
    navLinks.classList.toggle('open');
  });

  navLinks.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', () => navLinks.classList.remove('open'));
  });
}

// FAQ Accordion
document.querySelectorAll('.faq-question').forEach(button => {
  button.addEventListener('click', () => {
    const item = button.parentElement;
    item.classList.toggle('active');
    const icon = button.querySelector('span:last-child');
    if (icon) {
      icon.textContent = item.classList.contains('active') ? '−' : '+';
    }
  });
});

// Dark / Light Theme Toggle
const themeToggle = document.getElementById('themeToggle');
const savedTheme = localStorage.getItem('nova-theme');
if (savedTheme) {
  document.documentElement.setAttribute('data-theme', savedTheme);
}

if (themeToggle) {
  themeToggle.addEventListener('click', () => {
    const html = document.documentElement;
    const isDark = html.getAttribute('data-theme') === 'dark';
    const nextTheme = isDark ? 'light' : 'dark';
    html.setAttribute('data-theme', nextTheme);
    localStorage.setItem('nova-theme', nextTheme);
  });
}
